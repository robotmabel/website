/* order.html — the configurator, the spare-parts store, the cart and the account.
   Prices come from assets/data/order.json (generated by scripts/build_order.py)
   through assets/order-pricing.js; the checkout server prices the same cart again
   before it asks Stripe for anything, so this file never has the last word on money.
   Exposes window.__order for scripts/ordertest.py. */
(function () {
  'use strict';
  var $ = function (id) { return document.getElementById(id); };
  var P = window.MabelOrderPricing;
  var CART_KEY = 'mabel.cart.v1';
  var cat = null, tier = 'assembled', sel = null, cart = [], user = null, pay = 'full';
  var api = (function () {
    try {
      var q = new URLSearchParams(location.search).get('api');
      if (q) { localStorage.setItem('mabel.order.api', q); }
      return localStorage.getItem('mabel.order.api') || '';
    } catch (e) { return ''; }
  })();

  function usd(n) { return '$' + Math.round(n).toLocaleString('en-US'); }
  function delta(n) { return n === 0 ? 'No change' : (n > 0 ? '+ ' : '− ') + usd(Math.abs(n)); }
  function esc(s) { return String(s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
  function toast(msg) {
    var t = $('ordToast'); t.textContent = msg; t.classList.add('is-on');
    clearTimeout(toast._t); toast._t = setTimeout(function () { t.classList.remove('is-on'); }, 2200);
  }
  function step(id) { for (var i = 0; i < cat.steps.length; i++) if (cat.steps[i].id === id) return cat.steps[i]; }
  function findOpt(list, id) { for (var i = 0; i < list.length; i++) if (list[i].id === id) return list[i]; return null; }
  function tierOf(id) { for (var i = 0; i < cat.tiers.length; i++) if (cat.tiers[i].id === id) return cat.tiers[i]; }

  /* ── share link: ?c=tier.robot.compute.wrist.head.lidar.basecam.effector ── */
  var ORDER = ['robot', 'compute', 'wrist', 'head', 'lidar', 'basecam', 'effector'];
  function encode() { return [tier].concat(ORDER.map(function (k) { return sel[k]; })).join('.'); }
  function decode(s) {
    if (!s) return false;
    var parts = s.split('.');
    if (parts.length !== ORDER.length + 1 || !tierOf(parts[0])) return false;
    var trial = {};
    for (var i = 0; i < ORDER.length; i++) trial[ORDER[i]] = parts[i + 1];
    try { P.priceConfig(cat, parts[0], trial); } catch (e) { return false; }
    tier = parts[0]; sel = trial; return true;
  }

  /* ── configurator ── */
  function renderTier() {
    var el = $('cfgTier'); el.innerHTML = '';
    cat.tiers.forEach(function (t) {
      var b = document.createElement('button');
      b.type = 'button'; b.setAttribute('role', 'radio'); b.dataset.tier = t.id;
      b.setAttribute('aria-checked', String(t.id === tier));
      b.innerHTML = esc(t.name) + '<small>' + esc(t.lead) + '</small>';
      b.addEventListener('click', function () { tier = t.id; update(); });
      el.appendChild(b);
    });
  }
  function optButton(o, groupId, mode, current, img) {
    var b = document.createElement('button');
    b.type = 'button'; b.className = 'cfg-opt' + (img ? ' has-img' : ''); b.setAttribute('role', 'radio');
    b.dataset.group = groupId; b.dataset.opt = o.id;
    var on = current === o.id;
    b.setAttribute('aria-checked', String(on));
    var price;
    if (mode === 'abs') price = usd(o.price[tier]);
    else { var cur = findOpt(mode, current); price = on ? 'Selected' : delta(o.price[tier] - (cur ? cur.price[tier] : 0)); }
    if (mode !== 'abs' && !on && o.price[tier] === 0 && findOpt(mode, current).price[tier] === 0) price = 'Included';
    b.innerHTML = '<span class="cfg-radio" aria-hidden="true"></span>' +
      (img ? '<img class="cfg-opt-img" src="' + esc(img) + '" width="72" height="54" alt="" loading="lazy" />' : '') +
      '<span class="cfg-opt-body"><span class="cfg-opt-name">' + esc(o.name) + (o.tag ? '<span class="cfg-tag">' + esc(o.tag) + '</span>' : '') + '</span>' +
      '<span class="cfg-opt-spec">' + esc(o.spec) + '</span></span>' +
      '<span class="cfg-opt-price' + (price === 'No change' || price === 'Included' ? ' is-zero' : '') + '">' + price + '</span>';
    b.addEventListener('click', function () { sel[groupId] = o.id; update(); });
    return b;
  }
  function renderSteps() {
    var root = $('cfgSteps'); root.innerHTML = '';
    var applies = P.applies(cat, sel);
    cat.steps.forEach(function (s) {
      var sec = document.createElement('section'); sec.className = 'cfg-step'; sec.id = 'cfg-' + s.id;
      sec.innerHTML = '<div class="cfg-step-head"><span class="cfg-step-num">' + s.num + '</span><h3>' + esc(s.title) + '</h3><span>' + esc(s.help) + '</span></div>';
      if (s.options) {
        if (s.requires && !applies(s.requires)) {
          sec.innerHTML += '<div class="cfg-skip">Not on this body: an end effector needs arms. Pick a configuration with an upper body to choose one.</div>';
        } else {
          var g = document.createElement('div'); g.className = 'cfg-opts'; g.setAttribute('role', 'radiogroup'); g.setAttribute('aria-label', s.title);
          s.options.forEach(function (o) { g.appendChild(optButton(o, s.id, s.id === 'robot' ? 'abs' : s.options, sel[s.id], o.image)); });
          sec.appendChild(g);
        }
      } else {
        var shown = 0, skipped = [];
        s.groups.forEach(function (gr) {
          if (!applies(gr.requires)) { skipped.push(gr.title.toLowerCase()); return; }
          shown++;
          var w = document.createElement('div'); w.className = 'cfg-grp';
          w.innerHTML = '<h4 class="cfg-grp-title">' + esc(gr.title) + '</h4>' + (gr.note ? '<p class="cfg-grp-note">' + esc(gr.note) + '</p>' : '');
          var g2 = document.createElement('div'); g2.className = 'cfg-opts'; g2.setAttribute('role', 'radiogroup'); g2.setAttribute('aria-label', gr.title);
          gr.options.forEach(function (o) { g2.appendChild(optButton(o, gr.id, gr.options, sel[gr.id])); });
          w.appendChild(g2); sec.appendChild(w);
        });
        if (skipped.length) {
          var sk = document.createElement('div'); sk.className = 'cfg-skip'; sk.style.marginTop = shown ? '18px' : '0';
          sk.textContent = 'Not on this body: ' + skipped.join(', ') + '.';
          sec.appendChild(sk);
        }
      }
      root.appendChild(sec);
    });
  }
  function renderSummary() {
    var pc = P.priceConfig(cat, tier, sel);
    var t = tierOf(tier);
    var robot = findOpt(step('robot').options, sel.robot);
    $('cfgImg').src = robot.image;
    $('cfgLines').innerHTML = pc.lines.map(function (l) {
      return '<li><span>' + esc(l.label) + '</span><span>' + (l.price ? usd(l.price) : 'Included') + '</span></li>';
    }).join('');
    $('cfgTotal').textContent = usd(pc.total); $('cfgBarTotal').textContent = usd(pc.total);
    $('cfgTierName').textContent = t.name; $('cfgBarTier').textContent = t.name;
    $('cfgLead').textContent = t.lead + '. ' + t.blurb;
    try { history.replaceState(null, '', location.pathname + '?c=' + encode() + location.hash); } catch (e) {}
  }
  function update() { renderTier(); renderSteps(); renderSummary(); }
  function addConfig() {
    var pc = P.priceConfig(cat, tier, sel);
    cart.push({ kind: 'config', tier: tier, sel: JSON.parse(JSON.stringify(sel)), qty: 1 });
    saveCart(); openCart();   // the drawer opening IS the confirmation; a toast here would sit on its buttons
  }

  /* ── spare parts ── */
  var partsGroup = 'All', partsQ = '';
  function renderChips() {
    var el = $('partsChips'); el.innerHTML = '';
    ['All'].concat(cat.groups).forEach(function (g) {
      var b = document.createElement('button'); b.type = 'button'; b.className = 'parts-chip';
      b.textContent = g; b.setAttribute('aria-pressed', String(g === partsGroup));
      b.addEventListener('click', function () { partsGroup = g; renderChips(); renderParts(); });
      el.appendChild(b);
    });
  }
  function renderParts() {
    var grid = $('partsGrid'); grid.innerHTML = '';
    var q = partsQ.trim().toLowerCase();
    var list = cat.parts.filter(function (p) {
      if (partsGroup !== 'All' && p.group !== partsGroup) return false;
      if (!q) return true;
      return (p.name + ' ' + p.spec + ' ' + p.sku + ' ' + p.group).toLowerCase().indexOf(q) >= 0;
    });
    if (!list.length) { grid.innerHTML = '<div class="parts-empty">Nothing matches. Try a model number, or clear the filter.</div>'; return; }
    list.forEach(function (p) {
      var c = document.createElement('article'); c.className = 'parts-card'; c.dataset.sku = p.sku;
      c.innerHTML = '<span class="parts-grp">' + esc(p.group) + (p.ref ? ' · ' + esc(p.ref) : '') + '</span>' +
        '<span class="parts-name">' + esc(p.name) + '</span><span class="parts-spec">' + esc(p.spec) + (p.note ? ' ' + esc(p.note) : '') + '</span>' +
        '<div class="parts-row"><span class="parts-price">' + usd(p.price) + '<small>each</small></span>' +
        '<span class="parts-qty"><button type="button" aria-label="Fewer">−</button><output>1</output><button type="button" aria-label="More">+</button></span></div>' +
        '<div class="parts-row"><span></span><button type="button" class="parts-add">Add to cart</button></div>';
      var out = c.querySelector('output'), qb = c.querySelectorAll('.parts-qty button');
      qb[0].addEventListener('click', function () { out.value = Math.max(1, +out.value - 1); });
      qb[1].addEventListener('click', function () { out.value = Math.min(99, +out.value + 1); });
      c.querySelector('.parts-add').addEventListener('click', function () { addPart(p.sku, +out.value); });
      grid.appendChild(c);
    });
  }
  function addPart(sku, qty) {
    var hit = null;
    cart.forEach(function (it) { if (it.kind === 'part' && it.sku === sku) hit = it; });
    if (hit) hit.qty = Math.min(99, hit.qty + qty); else cart.push({ kind: 'part', sku: sku, qty: qty });
    saveCart(); toast('Added to cart — ' + P.part(cat, sku).name);
  }

  /* ── cart ── */
  function loadCart() { try { cart = JSON.parse(localStorage.getItem(CART_KEY) || '[]'); } catch (e) { cart = []; } if (!Array.isArray(cart)) cart = []; }
  var syncT = null;
  function saveCart() {
    try { localStorage.setItem(CART_KEY, JSON.stringify(cart)); } catch (e) {}
    renderCart();
    if (user && api) { clearTimeout(syncT); syncT = setTimeout(function () { req('PUT', '/api/cart', { items: cart }).catch(function () {}); }, 400); }
  }
  function cartCount() { return cart.reduce(function (a, it) { return a + (it.qty || 1); }, 0); }
  function renderCart() {
    var n = cartCount(), badge = $('dockCartN');
    badge.textContent = String(n); badge.hidden = n === 0;
    var list = $('cartList'); list.innerHTML = '';
    var hasConfig = cart.some(function (it) { return it.kind === 'config'; });
    $('cartPay').style.display = hasConfig ? '' : 'none';
    if (!hasConfig) pay = 'full';
    $('cartPay').querySelectorAll('button').forEach(function (b) { b.setAttribute('aria-checked', String(b.dataset.pay === pay)); });
    if (!cart.length) {
      list.innerHTML = '<div class="cart-empty">Your cart is empty. Configure a robot above, or add a spare part.</div>';
      $('cartTotal').textContent = '$0'; $('cartSumLabel').textContent = 'Total'; $('cartCheckout').disabled = true;
    } else {
      var priced;
      try { priced = P.priceCart(cat, cart); } catch (e) { cart = []; saveCart(); return; }
      priced.lines.forEach(function (l, i) {
        var it = cart[i];
        var d = document.createElement('div'); d.className = 'cart-item';
        d.innerHTML = '<div class="cart-item-name">' + esc(l.name) + '</div><div class="cart-item-desc">' + esc(l.desc) + '</div>' +
          '<div class="cart-item-row"><span class="cart-qty"><button type="button" aria-label="Fewer">−</button><output>' + l.qty + '</output><button type="button" aria-label="More">+</button></span>' +
          '<span class="cart-item-amt">' + usd(l.amount) + '</span></div><div class="cart-item-row"><button type="button" class="cart-rm">Remove</button><span></span></div>';
        var qb = d.querySelectorAll('.cart-qty button');
        qb[0].addEventListener('click', function () { if (it.qty > 1) { it.qty--; saveCart(); } });
        qb[1].addEventListener('click', function () { if (it.qty < 99) { it.qty++; saveCart(); } });
        d.querySelector('.cart-rm').addEventListener('click', function () { cart.splice(i, 1); saveCart(); });
        list.appendChild(d);
      });
      var due = pay === 'deposit' ? P.depositAmount(cat, priced.total) : priced.total;
      $('cartTotal').textContent = usd(due);
      $('cartSumLabel').textContent = pay === 'deposit' ? 'Deposit now · ' + usd(priced.total) + ' total' : 'Total';
      $('cartCheckout').disabled = false;
    }
    $('cartAcct').innerHTML = user ? 'Saved to <b>' + esc(user.email) + '</b>' : '<button type="button" id="cartSignIn">Sign in</button> to save your cart across devices.';
    var si = $('cartSignIn'); if (si) si.addEventListener('click', function () { closeCart(); openAcct(); });
  }
  function openCart() { $('cart').classList.add('is-open'); $('cartVeil').classList.add('is-open'); $('cart').setAttribute('aria-hidden', 'false'); $('cartMsg').hidden = true; }
  function closeCart() { $('cart').classList.remove('is-open'); $('cartVeil').classList.remove('is-open'); $('cart').setAttribute('aria-hidden', 'true'); }
  function cartMessage(text, err) { var m = $('cartMsg'); m.textContent = text; m.classList.toggle('is-err', !!err); m.hidden = false; }

  /* ── API ── */
  function req(method, path, body) {
    if (!api) return Promise.reject(new Error('no api'));
    return fetch(api + path, { method: method, credentials: 'include', headers: { 'Content-Type': 'application/json' },
                               body: body ? JSON.stringify(body) : undefined })
      .then(function (r) { return r.json().catch(function () { return {}; }).then(function (j) { if (!r.ok) throw new Error(j.detail || j.error || ('HTTP ' + r.status)); return j; }); });
  }
  function checkout() {
    if (!cart.length) return;
    var btn = $('cartCheckout'); btn.disabled = true; btn.textContent = 'Opening checkout…';
    req('POST', '/api/checkout', { items: cart, mode: pay, return_to: location.origin + location.pathname })
      .then(function (j) { if (!j.url) throw new Error('no checkout url'); location.href = j.url; })
      .catch(function (e) {
        btn.disabled = false; btn.textContent = 'Checkout';
        cartMessage('Checkout could not be reached (' + e.message + '). Your cart is saved on this device; please try again in a moment.', true);
      });
  }

  /* ── account ── */
  var acctMode = 'login';
  function openAcct() { $('acct').classList.add('is-open'); setTimeout(function () { var f = $('acctEmail'); if (f && !user) f.focus(); }, 60); }
  function closeAcct() { $('acct').classList.remove('is-open'); }
  function renderAcct() {
    $('acctGuest').hidden = !!user; $('acctUser').hidden = !user;
    $('dockAcctLabel').textContent = user ? 'Account' : 'Sign in';
    $('acctTitle').textContent = user ? 'Your account' : (acctMode === 'login' ? 'Sign in' : 'Create account');
    $('acctSubmit').textContent = acctMode === 'login' ? 'Sign in' : 'Create account';
    $('acctPass').setAttribute('autocomplete', acctMode === 'login' ? 'current-password' : 'new-password');
    document.querySelectorAll('#acct [role="tab"]').forEach(function (b) { b.setAttribute('aria-selected', String(b.dataset.mode === acctMode)); });
    if (user) {
      $('acctWho').textContent = user.email;
      var ol = $('acctOrders'); ol.innerHTML = '';
      (user.orders || []).forEach(function (o) {
        var li = document.createElement('li');
        li.innerHTML = '<div>' + esc(o.summary) + '</div><span>' + esc(o.created) + ' · ' + usd(o.total) + (o.mode === 'deposit' ? ' (deposit ' + usd(o.due) + ')' : '') +
          ' · <em class="' + (o.status === 'paid' ? 'is-paid' : '') + '">' + esc(o.status) + '</em></span>';
        ol.appendChild(li);
      });
      if (!(user.orders || []).length) ol.innerHTML = '<li><span>No orders yet.</span></li>';
    }
    renderCart();
  }
  function whoami() {
    if (!api) return Promise.resolve();
    return req('GET', '/api/auth/me').then(function (j) {
      user = j.user || null;
      if (user && j.cart && j.cart.length && !cart.length) { cart = j.cart; try { localStorage.setItem(CART_KEY, JSON.stringify(cart)); } catch (e) {} }
      else if (user && cart.length) req('PUT', '/api/cart', { items: cart }).catch(function () {});
      renderAcct();
    }).catch(function () { user = null; renderAcct(); });
  }
  function submitAcct(e) {
    e.preventDefault();
    var email = $('acctEmail').value.trim(), pw = $('acctPass').value, err = $('acctErr');
    err.textContent = '';
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) { err.textContent = 'Enter a valid email address.'; return; }
    if (pw.length < 8) { err.textContent = 'Use at least 8 characters.'; return; }
    if (!api) { err.textContent = 'Accounts are not connected on this copy of the site.'; return; }
    var btn = $('acctSubmit'); btn.disabled = true;
    req('POST', acctMode === 'login' ? '/api/auth/login' : '/api/auth/register', { email: email, password: pw })
      .then(function () { btn.disabled = false; $('acctPass').value = ''; return whoami(); })
      .then(function () { toast(acctMode === 'login' ? 'Signed in' : 'Account created'); })
      .catch(function (ex) { btn.disabled = false; err.textContent = ex.message; });
  }
  function logout() { req('POST', '/api/auth/logout').catch(function () {}).then(function () { user = null; renderAcct(); toast('Signed out'); }); }

  /* ── return from Stripe ── */
  function afterCheckout() {
    var q = new URLSearchParams(location.search), st = q.get('checkout');
    if (!st) return;
    if (st === 'cancel') { toast('Checkout cancelled. Your cart is saved.'); }
    if (st === 'success') {
      var sid = q.get('session_id');
      var done = $('ordDone'), txt = $('ordDoneText');
      done.hidden = false; txt.textContent = 'Thank you. A receipt is on its way to your email.';
      cart = []; saveCart();
      if (sid && api) req('GET', '/api/checkout/status?session_id=' + encodeURIComponent(sid)).then(function (j) {
        if (j.order) txt.textContent = 'Order #' + j.order.id + ' — ' + j.order.summary + '. ' + (j.order.status === 'paid' ? 'Paid ' + usd(j.order.due) + '.' : 'Payment ' + j.order.status + '.') + ' A receipt is on its way to your email.';
      }).catch(function () {});
      try { done.scrollIntoView({ block: 'center' }); } catch (e) {}
    }
    try { history.replaceState(null, '', location.pathname + location.hash); } catch (e) {}
  }

  /* ── wire ── */
  function wire() {
    $('cfgAdd').addEventListener('click', addConfig); $('cfgBarAdd').addEventListener('click', addConfig);
    $('cfgShare').addEventListener('click', function () {
      var url = location.origin + location.pathname + '?c=' + encode();
      var ok = function () { toast('Link copied'); }, no = function () { prompt('Copy this link', url); };
      if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(url).then(ok, no); else no();
    });
    document.querySelectorAll('[data-pick-tier]').forEach(function (b) {
      b.addEventListener('click', function () { tier = b.dataset.pickTier; update(); $('configure').scrollIntoView({ behavior: 'smooth', block: 'start' }); });
    });
    $('dockCart').addEventListener('click', openCart); $('cartClose').addEventListener('click', closeCart); $('cartVeil').addEventListener('click', closeCart);
    $('cartCheckout').addEventListener('click', checkout);
    $('cartPay').querySelectorAll('button').forEach(function (b) { b.addEventListener('click', function () { pay = b.dataset.pay; renderCart(); }); });
    $('dockAcct').addEventListener('click', openAcct); $('acctClose').addEventListener('click', closeAcct);
    $('acct').addEventListener('click', function (e) { if (e.target === $('acct')) closeAcct(); });
    document.querySelectorAll('#acct [role="tab"]').forEach(function (b) { b.addEventListener('click', function () { acctMode = b.dataset.mode; $('acctErr').textContent = ''; renderAcct(); }); });
    $('acctForm').addEventListener('submit', submitAcct); $('acctLogout').addEventListener('click', logout);
    $('partsSearch').addEventListener('input', function () { partsQ = this.value; renderParts(); });
    document.addEventListener('keydown', function (e) { if (e.key === 'Escape') { closeCart(); closeAcct(); } });
    document.body.classList.add('has-cfg-bar');
    /* The sticky total bar belongs to the configurator: it rides along only while
       that section is on screen, so the parts store and the fine print get the
       phone's full height back. */
    var bar = $('cfgBar'), cfgSec = $('configure');
    if ('IntersectionObserver' in window) {
      new IntersectionObserver(function (es) {
        var on = es[0].isIntersecting;
        bar.classList.toggle('is-on', on); document.body.classList.toggle('bar-on', on);
      }, { rootMargin: '-60px 0px -60px 0px' }).observe(cfgSec);
    } else { bar.classList.add('is-on'); document.body.classList.add('bar-on'); }
  }

  fetch('assets/data/order.json', { cache: 'no-cache' }).then(function (r) { return r.json(); }).then(function (c) {
    cat = c;
    if (!api) api = c.api || '';
    sel = P.defaults(cat);
    try { decode(new URLSearchParams(location.search).get('c')); } catch (e) {}
    loadCart(); wire(); update(); renderChips(); renderParts(); renderCart(); renderAcct();
    $('partsNote').textContent = 'List prices from the bill of materials priced ' + c.price_date + ', computed by scripts/build_order.py. Pass-through parts follow their vendor’s pricing and may move; parts we make are priced by us. ' + c.parts.length + ' parts.';
    afterCheckout(); whoami();
    window.__order = { get cat() { return cat; }, get sel() { return sel; }, get tier() { return tier; }, get cart() { return cart; }, get user() { return user; },
                       set api(v) { api = v; }, get api() { return api; }, update: update, openCart: openCart, closeCart: closeCart, openAcct: openAcct, closeAcct: closeAcct,
                       addPart: addPart, addConfig: addConfig, checkout: checkout,
                       set: function (k, v) { if (k === 'tier') tier = v; else sel[k] = v; update(); },
                       clear: function () { cart = []; saveCart(); } };
    document.dispatchEvent(new CustomEvent('order:ready'));
  }).catch(function (e) {
    $('cfgSteps').innerHTML = '<div class="cfg-skip">The catalog could not be loaded (' + esc(e.message) + '). Reload the page.</div>';
  });
})();
