/* ═══════════════════════════════════════════════════════════════════
   MABEL — PDF page slider
   Turns a pre-rendered page set into a browsable viewer: page-by-page
   navigation, a thumbnail strip, keyboard arrows, swipe, and a download.
   Pages are WebP renders generated by `tools/render_pdf_pages.sh`, so no
   PDF.js runtime is shipped and the whole thing works offline.

   Markup:
     <div class="pdfv"
          data-pdf="assets/pdf/MABEL_Wiring_Guide.pdf"
          data-pages="6"
          data-prefix="assets/pdf/pages/mabel-wiring-guide-"
          data-label="Wiring Guide"
          data-titles="Overview|Power|What each line feeds|..."></div>
═══════════════════════════════════════════════════════════════════ */
(function () {
  const hosts = document.querySelectorAll('.pdfv');
  if (!hosts.length) return;

  hosts.forEach((host) => {
    const total = parseInt(host.dataset.pages, 10);
    const prefix = host.dataset.prefix;
    const pdf = host.dataset.pdf;
    const label = host.dataset.label || 'Document';
    const titles = (host.dataset.titles || '').split('|');
    if (!total || !prefix) return;

    const src = (n) => `${prefix}${String(n).padStart(2, '0')}.webp`;
    let page = 1;

    host.innerHTML = `
      <div class="pdfv-bar">
        <div class="pdfv-meta">
          <span class="pdfv-label">${label}</span>
          <span class="pdfv-sub" data-role="title"></span>
        </div>
        <div class="pdfv-ctl">
          <button type="button" class="pdfv-btn" data-role="prev" aria-label="Previous page">‹</button>
          <span class="pdfv-count"><b data-role="n">1</b> / ${total}</span>
          <button type="button" class="pdfv-btn" data-role="next" aria-label="Next page">›</button>
          <a class="pdfv-dl" href="${pdf}" download>Download PDF</a>
          <a class="pdfv-dl ghost" href="${pdf}" target="_blank" rel="noopener">Open ↗</a>
        </div>
      </div>
      <div class="pdfv-stage" data-role="stage" tabindex="0" aria-label="${label} pages">
        <img data-role="img" alt="" />
      </div>
      <div class="pdfv-thumbs" data-role="thumbs"></div>`;

    const $ = (r) => host.querySelector(`[data-role="${r}"]`);
    const img = $('img'), thumbs = $('thumbs'), stage = $('stage');

    for (let i = 1; i <= total; i++) {
      const t = document.createElement('button');
      t.type = 'button';
      t.className = 'pdfv-thumb';
      t.dataset.page = i;
      t.setAttribute('aria-label', `Page ${i}${titles[i - 1] ? ': ' + titles[i - 1] : ''}`);
      t.innerHTML = `<img src="${src(i)}" loading="lazy" alt="" /><span>${i}</span>`;
      t.addEventListener('click', () => go(i));
      thumbs.appendChild(t);
    }

    function go(n) {
      page = Math.min(total, Math.max(1, n));
      img.src = src(page);
      img.alt = `${label}, page ${page}${titles[page - 1] ? ': ' + titles[page - 1] : ''}`;
      $('n').textContent = page;
      $('title').textContent = titles[page - 1] || '';
      $('prev').disabled = page === 1;
      $('next').disabled = page === total;
      thumbs.querySelectorAll('.pdfv-thumb').forEach((t) =>
        t.classList.toggle('on', Number(t.dataset.page) === page));
      const on = thumbs.querySelector('.pdfv-thumb.on');
      if (on) on.scrollIntoView({ block: 'nearest', inline: 'center', behavior: 'smooth' });
    }

    $('prev').addEventListener('click', () => go(page - 1));
    $('next').addEventListener('click', () => go(page + 1));
    stage.addEventListener('keydown', (e) => {
      if (e.key === 'ArrowLeft') { e.preventDefault(); go(page - 1); }
      if (e.key === 'ArrowRight') { e.preventDefault(); go(page + 1); }
    });

    // swipe
    let x0 = null;
    stage.addEventListener('touchstart', (e) => { x0 = e.touches[0].clientX; }, { passive: true });
    stage.addEventListener('touchend', (e) => {
      if (x0 === null) return;
      const dx = e.changedTouches[0].clientX - x0;
      if (Math.abs(dx) > 45) go(page + (dx < 0 ? 1 : -1));
      x0 = null;
    }, { passive: true });

    // preload the neighbours so paging feels instant
    stage.addEventListener('mouseenter', () => {
      [page - 1, page + 1].forEach((n) => {
        if (n >= 1 && n <= total) { const i = new Image(); i.src = src(n); }
      });
    });

    go(1);
  });
})();
